"""G-Code-Erzeugung: Pfade (Polylines) in Papier-Koordinaten -> Maschinen-G-Code."""
from .calibration import Calibration
from .pen import PenSettings


def _pen_target(calibration, pen, px, py):
    """Papier-Koordinate -> Maschinen-Ziel, verschoben um den Stift-X/Y-Offset.

    Der Stift sitzt auf Nozzle-Ebene, kann aber daneben montiert sein:
    die Nozzle muss um den Offset versetzt fahren, damit die STIFTSPITZE
    am kalibrierten Papier-Punkt landet.
    """
    mx, my = calibration.paper_to_machine(px, py)
    return (mx - pen.pen_offset_x, my - pen.pen_offset_y)


def _draw_groups(paths, calibration: Calibration, pen: PenSettings):
    """Eine Befehls-Gruppe pro Pfad: Stift hoch -> Anfahren -> runter -> zeichnen."""
    groups = []
    for path in paths:
        if len(path) < 2:
            continue
        # Verfahren zwischen Pfaden IMMER mit vollem pen_up_z (kein 1-mm-Hub,
        # der ueber unebenes Papier schleifen wuerde).
        cmds = list(pen.up_gcode())
        sx, sy = _pen_target(calibration, pen, path[0][0], path[0][1])
        cmds.append(f"G0 X{sx:.2f} Y{sy:.2f} F{pen.travel_speed * 60:.0f}")
        cmds.extend(pen.down_gcode())
        for (px, py) in path[1:]:
            mx, my = _pen_target(calibration, pen, px, py)
            cmds.append(f"G1 X{mx:.2f} Y{my:.2f} F{pen.draw_speed * 60:.0f}")
        groups.append(cmds)
    return groups


def plot_command_groups(paths, calibration: Calibration, pen: PenSettings):
    """Befehls-Gruppen fuer das LIVE-Plotten (Senden per Einzelbefehl).

    Kein G-Code-Upload, kein Druckstart: die Gruppen werden einzeln als
    Script an den Drucker geschickt. Sicher fuer den Stift:
    - es wird NUR X/Y gehomed (G28 X Y) – Z-Homen wuerde den Stift
      gegen das Bett druecken, wenn er niedriger als die Nozzle sitzt
    - das ALLERERSTE Kommando hebt den Stift auf pen_up_z, bevor
      irgendeine Fahrt stattfindet
    """
    head = ["G90", "G21", "G28 X Y", "M107"]
    head.extend(pen.up_gcode())
    groups = [head]
    groups.extend(_draw_groups(paths, calibration, pen))
    groups.append(pen.up_gcode() + ["G0 X0 Y0", "M84"])
    return groups


def color_segments(colors):
    """Farbliste -> aufeinanderfolgende Segmente [(farbe, [indizes]), ...].
    None/'' wird als 'keine Farbe' behandelt (immer ein eigenes Segment)."""
    segments = []
    for i, c in enumerate(colors):
        c = c or ""
        if segments and segments[-1][0] == c:
            segments[-1][1].append(i)
        else:
            segments.append((c, [i]))
    return segments


def plot_command_groups(paths, calibration: Calibration, pen: PenSettings,
                        colors=None, progress=None):
    """Befehls-Gruppen fuer das LIVE-Plotten (Senden per Einzelbefehl).

    items: Liste von Befehls-Listen; zwischen Farbsegmenten wird ein
    Pause-Marker ('pause', farbe) eingefuegt – der Plot stoppt dort,
    bis der Nutzer den Farbwechsel bestaetigt.
    progress: optionale Liste, parallel zu items: Anzahl gezeichneter Pfade
    NACH Ausfuehrung des jeweiligen Items (fuer die Live-Vorschau).
    order: Rueckgabe ist (items, order) falls order=True; order ist die Liste
    der Pfade in exakter Sende-Reihenfolge (fuer Live-Zeichnung).
    """
    head = ["G90", "G21", "G28 X Y", "M107"]
    head.extend(pen.up_gcode())
    items = [head]
    if progress is not None:
        progress.append(0)
    segments = color_segments(colors or [None] * len(paths))
    order, order_colors = [], []
    drawn = 0
    for si, (color, idxs) in enumerate(segments):
        seg_paths = [paths[i] for i in idxs]
        if color and si > 0:
            items.append(("pause", color))
            if progress is not None:
                progress.append(drawn)
        for gi, g in enumerate(_draw_groups(seg_paths, calibration, pen)):
            items.append(g)
            order.append(seg_paths[gi])
            order_colors.append(color or None)
            drawn += 1
            if progress is not None:
                progress.append(drawn)
    items.append(pen.up_gcode() + ["G0 X0 Y0", "M84"])
    if progress is not None:
        progress.append(drawn)
    return items, (order, order_colors)


def export_gcode(paths, calibration: Calibration, pen: PenSettings,
                 header_comment="Plotter Job", home_all=True):
    """paths: Liste von Polylines [(px, py), ...] in Papier-Einheiten 0..1."""
    lines = []
    lines.append(f"; {header_comment}")
    lines.append("; Generated by 3D-Plotter-App")
    lines.append(f"; Ecken: {len(calibration.points)}")
    lines.append("G90 ; absolute coordinates")
    lines.append("G21 ; mm")
    # G28 homed auch Z – das ist nur sicher, wenn der montierte Stift
    # mindestens so hoch wie die Nozzle ist (sonst Crash beim Z-Homen!).
    # Mit home_all=False wird nur X/Y gehomed.
    if home_all:
        lines.append("G28 ; home all axes (Stift-Bezug sicherstellen, Stift >= Noessel-Hoehe noetig)")
    else:
        lines.append("G28 X Y ; home nur X/Y (Z unberuehrt, z. B. wenn Stift unter Nozzle sitzt)")
    lines.append("M107 ; fans off")
    for group in _draw_groups(paths, calibration, pen):
        lines.extend(group)
    lines.extend(pen.up_gcode())
    lines.append("G0 X0 Y0 ; Parkposition")
    lines.append("; done")
    lines.append("M84 ; motors off")
    return "\n".join(lines) + "\n"


def save_gcode(filename, paths, calibration, pen, header_comment="Plotter Job"):
    gcode = export_gcode(paths, calibration, pen, header_comment)
    with open(filename, "w", encoding="utf-8") as f:
        f.write(gcode)
    return gcode
